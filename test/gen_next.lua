--[[
    gen_next.lua - writes progress/next/<cat>_<area>.lua: what Home and the area lists say about an entry without opening its
    page (a page is too much to decode for a list, and the step mappings all stay in memory, so the text cannot live in them).

        {[id] = {code = 'CoP 5-3', s = {['<tab>|<n>'] = "the step's first sentence"}}}

    `code` is the entry's short name, from the page's BG-wiki title; `s` has one line per mapped step, keyed as the step is
    addressed (at.tab, at.n), cut from the bullet ui/doc.lua's D.step_text finds. Generated: run it after a page or a mapping
    changes (test_steps.lua fails when a file is stale).

        cd addons/chronicle && "/c/Program Files (x86)/Lua/5.1/lua.exe" test/gen_next.lua
]]

package.path = './?.lua;' .. package.path
local D = require('ui/doc')

local G = {}

G.MAX = 140                     -- no window shows more of a Next line than this

-- the short series names; a page title of another shape (Assaults, Campaign, Wings of the Goddess) has no code
local SERIES = {
    {'^Promathia Mission (%S+)$', 'CoP'}, {'^Zilart Mission (%S+)$', 'RoZ'}, {'^Aht Urhgan Mission (%S+)$', 'ToAU'},
    {'^Seekers of Adoulin Mission (%S+)$', 'SoA'}, {'^Rhapsodies of Vanadiel Mission (%S+)$', 'RoV'},
    {'^The Voracious Resurgence Mission (%S+)$', 'TVR'}, {'^Crystalline Mission (%S+)$', 'ACP'},
    {'^Kupo Mission (%S+)$', 'MKD'}, {'^A Shantotto Ascension Mission (%S+)$', 'ASA'},
    {"^San d'Oria Mission (%S+)$", "San d'Oria"}, {'^Bastok Mission (%S+)$', 'Bastok'}, {'^Windurst Mission (%S+)$', 'Windurst'},
}

function G.code(title)
    for _, s in ipairs(SERIES) do
        local n = (title or ''):gsub('_', ' '):match(s[1])
        if n then return s[2] .. ' ' .. n end
    end
end

-- words that end in a full stop without ending the sentence
local ABBR = {mt = true, st = true, dr = true, mr = true, mrs = true, ms = true, lv = true, lvl = true, vs = true, approx = true, ex = true, eg = true, ie = true, etc = true}

-- A bullet's first sentence, whole when it is short enough: a Next line says what to do, the page says the rest
function G.first_sentence(text)
    text = text:gsub('%( +', '(')      -- a wiki icon dropped from just inside a bracket leaves its space
    local from = 1
    while true do
        local a, b = text:find('[.!?]%s+%(?%u', from)
        if not a then break end
        local word = text:sub(1, a - 1):match('([%a]+)$')
        if a >= 12 and not (word and (ABBR[word:lower()] or #word == 1)) then
            text = text:sub(1, a)
            break
        end
        from = b
    end
    if #text > G.MAX then
        text = text:sub(1, G.MAX):gsub('%s+%S*$', '')
    end
    return text
end

local function sorted(t, less)
    local out = {}
    for k in pairs(t) do out[#out + 1] = k end
    table.sort(out, less)
    return out
end

-- -> {[<cat>_<area>] = the file's text}
function G.build()
    local index = dofile('progress/index.lua')
    local pages = dofile('pages/index.lua')
    local files = {}
    for key, path in pairs(pages) do
        local cat, area, id = key:match('^(%a+)|([%w_]+)|(%d+)$')
        local mk = dofile(path)
        local e = {code = cat == 'mission' and G.code(mk.page) or nil}
        if index[key] then
            local doc = D.decode(mk)
            local m = dofile(('progress/%ss/%s/%s.lua'):format(cat, area, id))
            e.s = {}
            for _, s in ipairs(m.steps) do
                local t = D.step_text(doc, s.at.tab, s.at.n, s.at.fp)
                if t then e.s[(s.at.tab or '') .. '|' .. s.at.n] = G.first_sentence(t) end
            end
        end
        if e.code or e.s then
            local name = cat .. '_' .. area
            files[name] = files[name] or {}
            files[name][tonumber(id)] = e
        end
    end
    local out = {}
    for name, f in pairs(files) do
        local lines = {'-- Generated by test/gen_next.lua from pages/ and progress/. Do not edit.', 'return {'}
        for _, id in ipairs(sorted(f)) do
            local e = f[id]
            local parts = {}
            if e.code then parts[#parts + 1] = ('code = %q'):format(e.code) end
            if e.s then
                local s = {}
                for _, k in ipairs(sorted(e.s)) do s[#s + 1] = ('[%q] = %q'):format(k, e.s[k]) end
                parts[#parts + 1] = 's = {' .. table.concat(s, ', ') .. '}'
            end
            lines[#lines + 1] = ('    [%d] = {%s},'):format(id, table.concat(parts, ', '))
        end
        lines[#lines + 1] = '}'
        out[name] = table.concat(lines, '\n') .. '\n'
    end
    return out
end

-- progress/next/wants.lua: what each mapping can use (core/progress.lua's wants_of), so core/progress.lua keeps only what a mapping
-- can match without loading every mapping at init (review CORE-9). -> the file's text
function G.wants()
    local P = require('core/progress')
    local index = dofile('progress/index.lua')
    local keys = sorted(index)
    local function nums(t)
        local out = {}
        for _, n in ipairs(sorted(t)) do out[#out + 1] = ('%d'):format(n) end
        return '{' .. table.concat(out, ', ') .. '}'
    end
    local function strs(t)
        local out = {}
        for _, s in ipairs(sorted(t)) do out[#out + 1] = ('%q'):format(s) end
        return '{' .. table.concat(out, ', ') .. '}'
    end
    local lines = {'-- Generated by test/gen_next.lua from progress/. Do not edit.', 'return {'}
    for _, key in ipairs(keys) do
        local cat, area, id = key:match('^(%a+)|([%w_]+)|(%d+)$')
        local f = cat and loadfile(('progress/%ss/%s/%s.lua'):format(cat, area, id))
        local ok, m = false, nil
        if f then ok, m = pcall(f) end
        if ok and type(m) == 'table' then
            local w = P._wants_of(m)
            local parts = {}
            for _, kind in ipairs({'ki', 'item', 'event', 'zonein'}) do
                if next(w[kind]) then parts[#parts + 1] = kind .. ' = ' .. nums(w[kind]) end
            end
            if next(w.chat) then parts[#parts + 1] = 'chat = ' .. strs(w.chat) end
            if next(w.lines) then
                local ls = {}
                for _, l in ipairs(sorted(w.lines, function(a, b) return tostring(a) < tostring(b) end)) do
                    ls[#ls + 1] = type(l) == 'number' and ('[%d] = true'):format(l) or ('[%q] = true'):format(l)
                end
                parts[#parts + 1] = 'lines = {' .. table.concat(ls, ', ') .. '}'
            end
            if w.word then parts[#parts + 1] = 'word = true' end
            lines[#lines + 1] = ('    [%q] = {%s},'):format(key, table.concat(parts, ', '))
        end
    end
    lines[#lines + 1] = '}'
    return table.concat(lines, '\n') .. '\n'
end

if arg and arg[0] and arg[0]:find('gen_next') then
    os.execute('mkdir progress\\next 2> nul')
    do
        local f = assert(io.open('progress/next/wants.lua', 'wb'))
        f:write(G.wants())
        f:close()
        print('gen_next: progress/next/wants.lua')
    end
    local n = 0
    for name, text in pairs(G.build()) do
        local f = assert(io.open('progress/next/' .. name .. '.lua', 'wb'))
        f:write(text)
        f:close()
        n = n + 1
    end
    print('gen_next: ' .. n .. ' files')
end

return G
